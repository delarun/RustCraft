// Offline-mode identity, matching vanilla: UUID.nameUUIDFromBytes("OfflinePlayer:" + name).
// WebCrypto has no MD5, hence the small implementation below.

export function offlineUuid(username: string): string {
  const hash = md5(new TextEncoder().encode(`OfflinePlayer:${username}`));
  hash[6] = (hash[6]! & 0x0f) | 0x30; // version 3
  hash[8] = (hash[8]! & 0x3f) | 0x80; // IETF variant
  const hex = Array.from(hash, (b) => b.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

export function isValidUsername(name: string): boolean {
  return /^[A-Za-z0-9_]{3,16}$/.test(name);
}

const S = [
  7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22,
  5, 9, 14, 20, 5, 9, 14, 20, 5, 9, 14, 20, 5, 9, 14, 20,
  4, 11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23,
  6, 10, 15, 21, 6, 10, 15, 21, 6, 10, 15, 21, 6, 10, 15, 21,
];
const K = Array.from({ length: 64 }, (_, i) => Math.floor(Math.abs(Math.sin(i + 1)) * 2 ** 32) >>> 0);

export function md5(input: Uint8Array): Uint8Array {
  const paddedLength = (((input.length + 8) >> 6) + 1) << 6;
  const data = new Uint8Array(paddedLength);
  data.set(input);
  data[input.length] = 0x80;
  const view = new DataView(data.buffer);
  view.setUint32(paddedLength - 8, (input.length * 8) >>> 0, true);
  view.setUint32(paddedLength - 4, Math.floor((input.length * 8) / 2 ** 32), true);

  let a0 = 0x67452301, b0 = 0xefcdab89, c0 = 0x98badcfe, d0 = 0x10325476;
  for (let chunk = 0; chunk < paddedLength; chunk += 64) {
    let a = a0, b = b0, c = c0, d = d0;
    for (let i = 0; i < 64; i++) {
      let f: number, g: number;
      if (i < 16) { f = (b & c) | (~b & d); g = i; }
      else if (i < 32) { f = (d & b) | (~d & c); g = (5 * i + 1) % 16; }
      else if (i < 48) { f = b ^ c ^ d; g = (3 * i + 5) % 16; }
      else { f = c ^ (b | ~d); g = (7 * i) % 16; }
      const m = view.getUint32(chunk + g * 4, true);
      const sum = (a + f + K[i]! + m) | 0;
      a = d; d = c; c = b;
      b = (b + ((sum << S[i]!) | (sum >>> (32 - S[i]!)))) | 0;
    }
    a0 = (a0 + a) | 0; b0 = (b0 + b) | 0; c0 = (c0 + c) | 0; d0 = (d0 + d) | 0;
  }
  const out = new Uint8Array(16);
  const outView = new DataView(out.buffer);
  [a0, b0, c0, d0].forEach((word, i) => outView.setUint32(i * 4, word, true));
  return out;
}
