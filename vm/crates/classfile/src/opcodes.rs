/// Byte length of the instruction at `pc`, or `None` for an unknown opcode or
/// truncated code.
pub fn instruction_length(code: &[u8], pc: usize) -> Option<usize> {
    let op = *code.get(pc)?;
    let len = match op {
        BIPUSH | LDC | ILOAD..=ALOAD | ISTORE..=ASTORE | RET | NEWARRAY => 2,
        SIPUSH | LDC_W | LDC2_W | IINC | IFEQ..=JSR | GETSTATIC..=INVOKESTATIC | NEW | ANEWARRAY | CHECKCAST
        | INSTANCEOF | IFNULL | IFNONNULL => 3,
        MULTIANEWARRAY => 4,
        INVOKEINTERFACE | INVOKEDYNAMIC | GOTO_W | JSR_W => 5,
        WIDE => match *code.get(pc + 1)? {
            IINC => 6,
            ILOAD..=ALOAD | ISTORE..=ASTORE | RET => 4,
            _ => return None,
        },
        TABLESWITCH => {
            let base = (pc + 4) & !3;
            let low = read_i32(code, base + 4)?;
            let high = read_i32(code, base + 8)?;
            if high < low {
                return None;
            }
            base + 12 + 4 * (high as i64 - low as i64 + 1) as usize - pc
        }
        LOOKUPSWITCH => {
            let base = (pc + 4) & !3;
            let pairs = read_i32(code, base + 4)?;
            if pairs < 0 {
                return None;
            }
            base + 8 + 8 * pairs as usize - pc
        }
        0xca..=0xff => return None,
        _ => 1,
    };
    (pc + len <= code.len()).then_some(len)
}

fn read_i32(code: &[u8], at: usize) -> Option<i32> {
    Some(i32::from_be_bytes(code.get(at..at + 4)?.try_into().ok()?))
}

