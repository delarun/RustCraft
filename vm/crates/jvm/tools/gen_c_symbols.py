#!/usr/bin/env python3
"""Generates native/c_symbols.c: the browser build's table of C library
functions by name (shaderc, SPIRV-Cross's C API, stb), for dlsym. The table
is C, compiled against the libraries' headers, so the functions keep their
real wasm signatures (a Rust declaration with another one would make wasm-ld
substitute a trapping stub).

  tools/gen_c_symbols.py <wasm-libs dir>   (llvm-nm from its wasi-sdk)"""
import os, subprocess, sys

PREFIXES = ('shaderc_', 'spvc_', 'stbi_', 'stbir_')
LIBS = ['libshaderc.a', 'libspirv-cross-c.a', 'libstb.a']
# Exported but not declared in the public headers.
INTERNAL = {'stbi_write_png_to_mem', 'stbi_zlib_compress'}


def main(libs):
    nm = os.path.join(libs, 'wasi-sdk/bin/llvm-nm')
    names = set()
    for lib in LIBS:
        out = subprocess.run([nm, '--defined-only', '-g', os.path.join(libs, 'dist/lib', lib)], capture_output=True, text=True, check=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) == 3 and parts[1] == 'T' and parts[2].startswith(PREFIXES) and parts[2] not in INTERNAL:
                names.add(parts[2])
    names = sorted(names)
    lines = ['// Generated by tools/gen_c_symbols.py; do not edit.',
             '#include <stddef.h>',
             '#include <string.h>',
             '#include <shaderc/shaderc.h>',
             '#include <spirv_cross_c.h>',
             '#include <stb_image.h>',
             '#include <stb_image_write.h>',
             '#include <stb_image_resize2.h>',
             '',
             'static const struct { const char *name; void *function; } symbols[] = {']
    lines += [f'    {{"{n}", (void *){n}}},' for n in names]
    lines += ['};',
              '',
              '/* stb_image_write\'s compression level variable (LWJGL exposes it). */',
              'void *rjava_stbi_write_png_compression_level(void) { return &stbi_write_png_compression_level; }',
              'void *rjava_stbi_write_force_png_filter(void) { return &stbi_write_force_png_filter; }',
              'void *rjava_stbi_write_tga_with_rle(void) { return &stbi_write_tga_with_rle; }',
              '',
              '/* The function named `name`, or NULL. */',
              'void *rjava_c_symbol(const char *name) {',
              '    size_t lo = 0, hi = sizeof symbols / sizeof symbols[0];',
              '    while (lo < hi) {',
              '        size_t mid = (lo + hi) / 2;',
              '        int c = strcmp(name, symbols[mid].name);',
              '        if (c == 0) return symbols[mid].function;',
              '        if (c < 0) hi = mid; else lo = mid + 1;',
              '    }',
              '    return NULL;',
              '}']
    target = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'native/c_symbols.c')
    with open(target, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {target}: {len(names)} functions')


if __name__ == '__main__':
    main(sys.argv[1])
