#!/usr/bin/env python3
"""Generates src/web/invoke.rs: the browser build's org.lwjgl.system.JNI
natives (invoke*/call*), which call a C function by address, from the
signatures in an LWJGL jar.

  tools/gen_lwjgl_invoke.py <lwjgl-<version>.jar>

LWJGL names each method by letters for its long, short, byte and array
parameters (P/N pointer, J int64, C/S short, U/B byte, P array) and for its
return type; the last long is the function. Under wasm32 a function address
is an index into the indirect function table and a pointer is 32 bits, so
each native transmutes the address to an `extern "C" fn` of the wasm-level
signature and calls it."""
import os, re, subprocess, sys, tempfile, zipfile

JAVA = {'byte': 'B', 'short': 'S', 'char': 'C', 'int': 'I', 'long': 'J', 'float': 'F', 'double': 'D', 'boolean': 'Z', 'void': 'V'}
LETTERED = {'long', 'short', 'byte'}


def methods(jar):
    with tempfile.TemporaryDirectory() as tmp:
        with zipfile.ZipFile(jar) as z:
            z.extract('org/lwjgl/system/JNI.class', tmp)
        out = subprocess.run(['javap', '-p', os.path.join(tmp, 'org/lwjgl/system/JNI.class')], capture_output=True, text=True, check=True).stdout
    for line in out.splitlines():
        m = re.match(r'\s*public static native (\S+) (\w+)\((.*)\);', line)
        if m:
            yield m.group(1), m.group(2), [p.strip() for p in m.group(3).split(',') if p.strip()]


def descriptor(t):
    if t.endswith('[]'):
        return '[' + descriptor(t[:-2])
    return JAVA[t]


def generate(jar):
    out = ['// Generated by tools/gen_lwjgl_invoke.py from ' + os.path.basename(jar) + '; do not edit.',
           '',
           'use super::invoke_support::*;',
           'use crate::interp::{JResult, Thread};',
           '',
           'pub(super) fn register(n: &mut crate::native::Natives) {']
    bodies = []
    for index, (ret, name, params) in enumerate(methods(jar)):
        letters = re.match(r'(?:invoke|call)([A-Z]*)$', name).group(1)
        *args, function = params
        assert function == 'long', name
        pos = 0
        slot = 0
        c_params = []   # (rust type, expression)
        prelude = []
        for p in args:
            letter = None
            if p in LETTERED or p.endswith('[]'):
                letter = letters[pos]
                pos += 1
            if p.endswith('[]'):
                prelude.append(f'    let p{slot} = array(t, a[{slot}]);\n')
                c_params.append(('u32', f'p{slot}'))
            elif p == 'long':
                c_params.append(('i64', f'a[{slot}] as i64') if letter == 'J' else ('u32', f'a[{slot}] as u32'))
            elif p == 'short':
                c_params.append(('i32', f'a[{slot}] as u16 as i32' if letter == 'C' else f'a[{slot}] as i16 as i32'))
            elif p == 'byte':
                c_params.append(('i32', f'a[{slot}] as u8 as i32' if letter == 'U' else f'a[{slot}] as i8 as i32'))
            elif p == 'boolean':
                c_params.append(('i32', f'(a[{slot}] as u8 != 0) as i32'))
            elif p == 'int':
                c_params.append(('i32', f'a[{slot}] as i32'))
            elif p == 'float':
                c_params.append(('f32', f'f32::from_bits(a[{slot}] as u32)'))
            elif p == 'double':
                c_params.append(('f64', f'f64::from_bits(a[{slot}])'))
            else:
                raise SystemExit(f'{name}: parameter {p}')
            slot += 2 if p in ('long', 'double') else 1
        assert pos == len(letters) - 1, (name, params)
        r = letters[-1]
        rust_ret, conv = {
            'V': ('', 'None'),
            'I': (' -> i32', 'Some(r as u32 as u64)'),
            'Z': (' -> i32', 'Some((r & 0xff != 0) as u64)'),
            'J': (' -> i64', 'Some(r as u64)'),
            'P': (' -> u32', 'Some(r as u64)'),
            'N': (' -> u32', 'Some(r as u64)'),
            'C': (' -> i32', 'Some(r as u16 as u64)'),
            'S': (' -> i32', 'Some(r as i16 as i32 as u32 as u64)'),
            'U': (' -> i32', 'Some(r as u8 as u64)'),
            'B': (' -> i32', 'Some(r as i8 as i32 as u32 as u64)'),
            'F': (' -> f32', 'Some(r.to_bits() as u64)'),
            'D': (' -> f64', 'Some(r.to_bits())'),
        }[r]
        desc = '(' + ''.join(descriptor(p) for p in params) + ')' + descriptor(ret)
        types = ', '.join(t for t, _ in c_params)
        values = ', '.join(e for _, e in c_params)
        call = f'f({values})'
        result = f'let r = call(t, || unsafe {{ {call} }});\n    Ok({conv})' if rust_ret else f'call(t, || unsafe {{ {call} }});\n    Ok(None)'
        bodies.append(f'''
fn n{index}(t: &mut Thread<'_>, a: &[u64]) -> JResult<Option<u64>> {{
    // SAFETY: LWJGL passes a function of this signature.
    let f: unsafe extern "C" fn({types}){rust_ret} = unsafe {{ function(t, a[{slot}])? }};
{''.join(prelude)}    {result}
}}''')
        out.append(f'    n.add("org/lwjgl/system/JNI.{name}{desc}", n{index});')
    out.append('}')
    out.extend(bodies)
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    target = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src/web/invoke.rs')
    with open(target, 'w') as f:
        f.write(generate(sys.argv[1]))
    print('wrote', target)
